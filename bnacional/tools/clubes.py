import re
import unicodedata


def nk(s):
    s = unicodedata.normalize("NFD", s or "")
    s = "".join(c for c in s if unicodedata.category(c) != "Mn").lower()
    return re.sub(r"[^a-z0-9 ]", " ", s).strip()


def nkk(s):
    return re.sub(r"\s+", " ", nk(s))


